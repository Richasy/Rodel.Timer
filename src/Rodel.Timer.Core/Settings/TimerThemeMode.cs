namespace Rodel.Timer.Core.Settings;

/// <summary>The application's theme preference.</summary>
public enum TimerThemeMode
{
    /// <summary>Follow the operating system's current theme.</summary>
    System,

    /// <summary>Always use the light theme, regardless of the operating system setting.</summary>
    Light,

    /// <summary>Always use the dark theme, regardless of the operating system setting.</summary>
    Dark,
}
